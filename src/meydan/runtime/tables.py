"""Runtime tables, defined on the instance's own MetaData so its Alembic migrates them.

    from meydan.runtime import define_tables
    runtime_tables = define_tables(Base.metadata)

Postgres 18+ (ids are generated by `uuidv7()`, time-ordered, so `ORDER BY id` is insertion
order even within one transaction).

Two groups (docs/identity.md):
- **Who:** actors (person, agent, org), identities (immutable addresses on a channel) and claims
  (append-only evidence that an identity belongs to an actor; the only place who-is-who is decided).
- **What was said:** conversations with their participants (identities), the inbox and the outbox.
  Messages point to identities, never to actors, so re-linking identities never rewrites history.
- **What it took:** one row per turn (timing, status, tokens, cost) and one per model call
  (docs/observe.md), written in the same transaction as the reply.
- **Who may use the app:** sign-ins (proof of control through a channel), sessions and grants
  (scopes per actor) (docs/auth.md). Secrets are stored only as hashes.
"""

from dataclasses import dataclass

from sqlalchemy import (
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    MetaData,
    Numeric,
    PrimaryKeyConstraint,
    String,
    Table,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

OUTBOX_STATUSES = ("pending", "sent", "delivered", "read", "failed", "dead")
ACTOR_KINDS = ("person", "agent", "org")
CLAIM_STATES = ("proposed", "active")
CLAIM_END_REASONS = ("revoked", "superseded", "dismissed", "expired")
CONVERSATION_KINDS = ("direct", "thread", "group")
PARTICIPANT_ROLES = ("self", "peer", "observer")
TURN_STATUSES = ("replied", "failed", "gave_up")
COST_SOURCES = ("provider", "estimate", "mixed")


@dataclass(frozen=True)
class RuntimeTables:
    actors: Table
    identities: Table
    claims: Table
    conversations: Table
    participants: Table
    inbox: Table
    outbox: Table
    turns: Table
    usage: Table
    sign_ins: Table
    sessions: Table
    grants: Table


def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN (" + ", ".join(f"'{v}'" for v in values) + ")"


def define_tables(metadata: MetaData, prefix: str = "meydan_") -> RuntimeTables:
    def id_col() -> Column:
        return Column("id", UUID(as_uuid=True), primary_key=True, server_default=text("uuidv7()"))

    def ref(table: str, **kw) -> ForeignKey:
        return ForeignKey(f"{prefix}{table}.id", **kw)

    def now_col(name: str) -> Column:
        return Column(name, DateTime(timezone=True), nullable=False, server_default=func.now())

    actors = Table(
        f"{prefix}actors",
        metadata,
        id_col(),
        Column("kind", String(20), nullable=False),
        Column("name", String(255)),  # display only
        now_col("created_at"),
        now_col("updated_at"),
        CheckConstraint(_in("kind", ACTOR_KINDS), name="kind"),
    )

    identities = Table(
        f"{prefix}identities",
        metadata,
        id_col(),
        # tel | wa-bsuid | wa-pnid | mailto | agent | ... (the connector's address scheme)
        Column("scheme", String(30), nullable=False),
        # Namespace that makes `value` unique where the channel scopes it (e.g. the Meta business
        # portfolio for BSUIDs); "" when the value is global (tel, mailto).
        Column("scope", String(100), nullable=False, server_default=""),
        Column("value", String(255), nullable=False),  # normalized: E.164, lowercased email, ...
        Column(
            "attrs", JSONB, nullable=False, server_default=text("'{}'::jsonb")
        ),  # names: no keys
        now_col("first_seen_at"),
        now_col("last_seen_at"),
        Column("retired_at", DateTime(timezone=True)),  # superseded or closed; history stays
        UniqueConstraint("scheme", "scope", "value"),
    )

    claims = Table(
        f"{prefix}claims",
        metadata,
        id_col(),
        Column("identity_id", UUID(as_uuid=True), ref("identities"), nullable=False),
        Column("actor_id", UUID(as_uuid=True), ref("actors"), nullable=False),
        Column("state", String(20), nullable=False),
        # first_contact | channel_cooccurrence | endpoint | imported | proof_of_control | ...
        Column("basis", String(40), nullable=False),
        Column("evidence", JSONB, nullable=False, server_default=text("'{}'::jsonb")),  # refs only
        Column("by_actor_id", UUID(as_uuid=True), ref("actors")),  # who decided; null = a rule
        Column("batch_id", UUID(as_uuid=True)),  # claims written together are undone together
        now_col("valid_from"),
        Column("valid_to", DateTime(timezone=True)),
        Column("end_reason", String(20)),
        CheckConstraint(_in("state", CLAIM_STATES), name="state"),
        CheckConstraint(
            f"end_reason IS NULL OR {_in('end_reason', CLAIM_END_REASONS)}", name="end"
        ),
    )
    # Exactly one current owner per identity.
    Index(
        f"uq_{prefix}claims_owner",
        claims.c.identity_id,
        unique=True,
        postgresql_where=(claims.c.state == "active") & claims.c.valid_to.is_(None),
    )
    Index(f"ix_{prefix}claims_actor", claims.c.actor_id)

    conversations = Table(
        f"{prefix}conversations",
        metadata,
        id_col(),
        Column("kind", String(20), nullable=False, server_default="direct"),
        Column("channel", String(20), nullable=False),
        # Our side: the number/mailbox/agent the conversation happens on (reply affinity).
        Column("endpoint_identity_id", UUID(as_uuid=True), ref("identities"), nullable=False),
        Column("thread_key", String(255)),  # email thread root, group id, ...; null for direct
        now_col("created_at"),
        CheckConstraint(_in("kind", CONVERSATION_KINDS), name="kind"),
    )
    Index(
        f"uq_{prefix}conversations_thread",
        conversations.c.channel,
        conversations.c.thread_key,
        unique=True,
        postgresql_where=conversations.c.thread_key.is_not(None),
    )

    participants = Table(
        f"{prefix}participants",
        metadata,
        Column(
            "conversation_id",
            UUID(as_uuid=True),
            ref("conversations", ondelete="CASCADE"),
            nullable=False,
        ),
        Column("identity_id", UUID(as_uuid=True), ref("identities"), nullable=False),
        Column("role", String(20), nullable=False, server_default="peer"),
        now_col("joined_at"),
        Column("left_at", DateTime(timezone=True)),
        PrimaryKeyConstraint("conversation_id", "identity_id"),
        CheckConstraint(_in("role", PARTICIPANT_ROLES), name="role"),
    )
    Index(f"ix_{prefix}participants_identity", participants.c.identity_id)

    inbox = Table(
        f"{prefix}inbox",
        metadata,
        id_col(),
        Column("channel", String(20), nullable=False),
        Column("message_id", String(255), nullable=False),
        Column("conversation_id", UUID(as_uuid=True), ref("conversations"), nullable=False),
        Column("sender_identity_id", UUID(as_uuid=True), ref("identities"), nullable=False),
        # Address values, kept beside the identities for replies and logs (both are immutable).
        Column("to", String(64), nullable=False),  # our endpoint the person wrote to
        Column("sender", String(255), nullable=False),
        Column("sender_name", String(255)),
        Column("kind", String(30), nullable=False),
        Column("text", Text, nullable=False, server_default=""),
        Column("payload", JSONB(none_as_null=True)),
        Column("sent_at", DateTime(timezone=True), nullable=False),
        now_col("received_at"),
        # Presence timeline (database clock): when we showed "seen" and "typing…" for it.
        Column("read_at", DateTime(timezone=True)),
        Column("typing_at", DateTime(timezone=True)),
        # Set when a turn consumed this message (or gave up on it).
        Column("processed_at", DateTime(timezone=True)),
        Column("attempts", Integer, nullable=False, server_default="0"),
        Column("error", Text),
        # Idempotent Receiver: channels deliver at least once.
        UniqueConstraint("channel", "message_id"),
    )
    Index(
        f"ix_{prefix}inbox_unprocessed",
        inbox.c.conversation_id,
        inbox.c.received_at,
        postgresql_where=inbox.c.processed_at.is_(None),
    )

    outbox = Table(
        f"{prefix}outbox",
        metadata,
        id_col(),
        Column("channel", String(20), nullable=False),
        Column("conversation_id", UUID(as_uuid=True), ref("conversations"), nullable=False),
        Column("recipient_identity_id", UUID(as_uuid=True), ref("identities")),
        Column("from_number", String(64), nullable=False),  # reply affinity
        Column("to", String(255), nullable=False),
        # One outbound turn (an agent's reply) can be several messages, e.g. WhatsApp bubbles.
        Column("turn_id", UUID(as_uuid=True)),
        Column("seq", Integer, nullable=False, server_default="0"),
        Column("message", JSONB, nullable=False),  # Outbound.to_payload()
        Column("status", String(20), nullable=False, server_default="pending"),
        Column("channel_message_id", String(255), unique=True),  # e.g. wamid once sent
        Column("attempts", Integer, nullable=False, server_default="0"),
        # Not before: paces bubbles and schedules retries. Always computed on the database clock.
        now_col("next_attempt_at"),
        Column("last_error", Text),
        now_col("created_at"),
        Column("sent_at", DateTime(timezone=True)),
        now_col("updated_at"),
        CheckConstraint(_in("status", OUTBOX_STATUSES), name="status"),
    )
    Index(
        f"ix_{prefix}outbox_pending",
        outbox.c.conversation_id,
        outbox.c.id,
        postgresql_where=outbox.c.status == "pending",
    )
    turns = Table(
        f"{prefix}turns",
        metadata,
        # The turn's id is also the outbox's turn_id for the reply it produced.
        Column("id", UUID(as_uuid=True), primary_key=True),
        Column("conversation_id", UUID(as_uuid=True), ref("conversations"), nullable=False),
        Column("actor_id", UUID(as_uuid=True), ref("actors")),  # who it was for, as settled then
        Column("channel", String(20), nullable=False),
        Column("started_at", DateTime(timezone=True), nullable=False),
        Column("finished_at", DateTime(timezone=True), nullable=False),
        Column("status", String(20), nullable=False),
        Column("error", Text),
        Column("messages_in", Integer, nullable=False, server_default="0"),
        Column("messages_out", Integer, nullable=False, server_default="0"),
        Column("model_calls", Integer, nullable=False, server_default="0"),
        Column("model", String(120)),  # the last model that answered
        Column("input_tokens", Integer, nullable=False, server_default="0"),
        Column("output_tokens", Integer, nullable=False, server_default="0"),
        Column("cost_usd", Numeric(14, 8)),  # None: no cost known
        Column("cost_source", String(20)),
        CheckConstraint(_in("status", TURN_STATUSES), name="status"),
        CheckConstraint(f"cost_source IS NULL OR {_in('cost_source', COST_SOURCES)}", name="cost"),
    )
    Index(f"ix_{prefix}turns_conversation", turns.c.conversation_id, turns.c.started_at)
    Index(f"ix_{prefix}turns_started", turns.c.started_at)

    usage = Table(
        f"{prefix}usage",
        metadata,
        id_col(),
        Column("turn_id", UUID(as_uuid=True), ref("turns", ondelete="CASCADE"), nullable=False),
        now_col("at"),
        Column("provider", String(60)),
        Column("model", String(120)),
        Column("input_tokens", Integer, nullable=False, server_default="0"),
        Column("output_tokens", Integer, nullable=False, server_default="0"),
        Column("cache_read_tokens", Integer, nullable=False, server_default="0"),
        Column("cache_write_tokens", Integer, nullable=False, server_default="0"),
        Column("reasoning_tokens", Integer, nullable=False, server_default="0"),
        Column("cost_usd", Numeric(14, 8)),
        Column("cost_source", String(20)),
        CheckConstraint(
            f"cost_source IS NULL OR {_in('cost_source', COST_SOURCES[:2])}", name="cost"
        ),
    )
    Index(f"ix_{prefix}usage_turn", usage.c.turn_id)

    sign_ins = Table(
        f"{prefix}sign_ins",
        metadata,
        id_col(),
        Column("code_hash", String(64), nullable=False, unique=True),  # what the person sends
        Column("browser_hash", String(64), nullable=False, unique=True),  # what the browser holds
        Column("audience", String(40), nullable=False),  # e.g. "ops": the scope a signer must hold
        now_col("created_at"),
        Column("expires_at", DateTime(timezone=True), nullable=False),
        Column("confirmed_at", DateTime(timezone=True)),
        Column("actor_id", UUID(as_uuid=True), ref("actors")),  # who confirmed it
        Column("identity_id", UUID(as_uuid=True), ref("identities")),  # from which address
        Column("claimed_at", DateTime(timezone=True)),  # when the browser got its session
    )

    sessions = Table(
        f"{prefix}sessions",
        metadata,
        id_col(),
        Column("token_hash", String(64), nullable=False, unique=True),
        Column("actor_id", UUID(as_uuid=True), ref("actors"), nullable=False),
        Column("audience", String(40), nullable=False),
        now_col("created_at"),
        now_col("last_seen_at"),
        Column("expires_at", DateTime(timezone=True), nullable=False),
        Column("revoked_at", DateTime(timezone=True)),
        Column("label", String(200)),  # e.g. the browser, for "where am I signed in"
    )
    Index(f"ix_{prefix}sessions_actor", sessions.c.actor_id)

    grants = Table(
        f"{prefix}grants",
        metadata,
        id_col(),
        Column("actor_id", UUID(as_uuid=True), ref("actors"), nullable=False),
        Column("scope", String(80), nullable=False),  # e.g. "ops", "costs:read"
        Column("granted_by", UUID(as_uuid=True), ref("actors")),  # None: granted by an operator CLI
        now_col("created_at"),
        Column("revoked_at", DateTime(timezone=True)),
    )
    Index(
        f"uq_{prefix}grants_open",
        grants.c.actor_id,
        grants.c.scope,
        unique=True,
        postgresql_where=grants.c.revoked_at.is_(None),
    )

    return RuntimeTables(
        actors=actors,
        identities=identities,
        claims=claims,
        conversations=conversations,
        participants=participants,
        inbox=inbox,
        outbox=outbox,
        turns=turns,
        usage=usage,
        sign_ins=sign_ins,
        sessions=sessions,
        grants=grants,
    )
