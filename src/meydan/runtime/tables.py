"""Runtime tables, defined on the instance's own MetaData so its Alembic migrates them.

    from meydan.runtime import define_tables
    runtime_tables = define_tables(Base.metadata)

Postgres 18+ (ids are generated by `uuidv7()`, time-ordered, so `ORDER BY id` is insertion
order even within one transaction).
"""

from dataclasses import dataclass

from sqlalchemy import (
    CheckConstraint,
    Column,
    DateTime,
    Index,
    Integer,
    MetaData,
    String,
    Table,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID

OUTBOX_STATUSES = ("pending", "sent", "delivered", "read", "failed", "dead")


@dataclass(frozen=True)
class RuntimeTables:
    inbox: Table
    outbox: Table


def define_tables(metadata: MetaData, prefix: str = "meydan_") -> RuntimeTables:
    def id_col() -> Column:
        return Column("id", UUID(as_uuid=True), primary_key=True, server_default=text("uuidv7()"))

    inbox = Table(
        f"{prefix}inbox",
        metadata,
        id_col(),
        Column("channel", String(20), nullable=False),
        Column("message_id", String(255), nullable=False),
        Column("conversation_key", String(255), nullable=False),
        Column("to", String(64), nullable=False),  # our number the person wrote to
        Column("sender", String(64), nullable=False),
        Column("sender_name", String(255)),
        Column("kind", String(30), nullable=False),
        Column("text", Text, nullable=False, server_default=""),
        Column("payload", JSONB(none_as_null=True)),
        Column("sent_at", DateTime(timezone=True), nullable=False),
        Column("received_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
        # Set when a turn consumed this message (or gave up on it).
        Column("processed_at", DateTime(timezone=True)),
        Column("attempts", Integer, nullable=False, server_default="0"),
        Column("error", Text),
        # Idempotent Receiver: Meta delivers at least once.
        UniqueConstraint("channel", "message_id"),
    )
    Index(
        f"ix_{prefix}inbox_unprocessed",
        inbox.c.conversation_key,
        inbox.c.received_at,
        postgresql_where=inbox.c.processed_at.is_(None),
    )

    outbox = Table(
        f"{prefix}outbox",
        metadata,
        id_col(),
        Column("channel", String(20), nullable=False),
        Column("conversation_key", String(255), nullable=False),
        Column("from_number", String(64), nullable=False),  # reply affinity
        Column("to", String(64), nullable=False),
        Column("message", JSONB, nullable=False),  # Outbound.to_payload()
        Column("status", String(20), nullable=False, server_default="pending"),
        Column("channel_message_id", String(255), unique=True),  # wamid once sent
        Column("attempts", Integer, nullable=False, server_default="0"),
        # Not before: paces bubbles and schedules retries.
        Column(
            "next_attempt_at", DateTime(timezone=True), nullable=False, server_default=func.now()
        ),
        Column("last_error", Text),
        Column("created_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
        Column("sent_at", DateTime(timezone=True)),
        Column("updated_at", DateTime(timezone=True), nullable=False, server_default=func.now()),
        CheckConstraint(
            "status IN (" + ", ".join(f"'{s}'" for s in OUTBOX_STATUSES) + ")",
            name="status",
        ),
    )
    Index(
        f"ix_{prefix}outbox_pending",
        outbox.c.conversation_key,
        outbox.c.id,
        postgresql_where=outbox.c.status == "pending",
    )
    return RuntimeTables(inbox=inbox, outbox=outbox)
